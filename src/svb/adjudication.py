"""Data-only scientific-review ingestion. Attestations are not identity proofs.

No reviews are bundled or generated by this module. Production rejects software
fixtures. Agreement is descriptive and never creates or overwrites gold labels.
"""
from __future__ import annotations
import argparse
from collections import Counter
from itertools import combinations
import hashlib
import json
from pathlib import Path
import re
from .core import Invalid, LABELS, canonical, loads
from .taxonomy import VERSION, obj, text, strings

ROOT = Path(__file__).resolve().parents[2]
RELATIONS = ('support_only', 'opposition_only', 'neither', 'both')
CATEGORY_RELATIONS = ('single_defensible', 'simultaneously_applicable', 'alternative_interpretations', 'none_fit')
ISSUES = ('taxonomy_overlap', 'ambiguous_target', 'reference_error_suspected', 'source_incomplete', 'irreconcilable_interpretation')
UNCERTAINTIES = ('low', 'moderate', 'high', 'not_assessable')
DECLARATION_KEYS = {'human_attestation', 'independent_work', 'saw_other_reviews',
                    'source_exposure', 'author_label_exposure', 'candidate_identity_exposure',
                    'conflicts', 'expertise_scope'}
BASE_JUDGMENT = {'packet_id', 'packet_sha256', 'assessment_status', 'reviewer_uncertainty', 'rationale', 'citations'}
REFERENCE_JUDGMENT = BASE_JUDGMENT | {'legacy_labels', 'category_relation', 'evidence_relation',
    'supported_scope', 'missing_assumptions', 'uncertainty_explanation', 'issues', 'proposed_disposition', 'proposed_revision'}
CANDIDATE_JUDGMENT = BASE_JUDGMENT | {'candidate_id', 'candidate_sha256', 'reasoning_validity',
    'attribution_validity', 'scope_handling', 'uncertainty_handling'}


def digest_bytes(data): return hashlib.sha256(data).hexdigest()
def digest_json(x): return digest_bytes(canonical(x))


def load_file(path):
    p = Path(path)
    if not p.is_file() or p.stat().st_size > 2 * 1024 * 1024:
        raise Invalid('review JSON must be a file of at most 2 MiB')
    try: return loads(p.read_text())
    except (ValueError, UnicodeError, RecursionError) as e: raise Invalid('invalid review JSON') from e


def code(x):
    if not isinstance(x, str) or re.fullmatch(r'[A-Za-z][A-Za-z0-9_-]{2,31}', x) is None:
        raise Invalid('anonymous reviewer code required, not an email or personal identifier')


def validate_context(context):
    obj(context, {'schema_version', 'pilot_id', 'packets', 'candidates'}, 'review context')
    if context['schema_version'] != VERSION: raise Invalid('context version mismatch')
    text(context['pilot_id'], 'pilot ID')
    if not isinstance(context['packets'], list) or not context['packets']: raise Invalid('nonempty review packets required')
    packets = {}
    for p in context['packets']:
        obj(p, {'packet_id', 'packet_sha256', 'packet', 'source_family'}, 'context packet')
        text(p['packet_id'], 'packet ID'); text(p['source_family'], 'source family')
        if p['packet_id'] in packets or digest_json(p['packet']) != p['packet_sha256']:
            raise Invalid('duplicate or corrupted packet')
        if p['packet'].get('packet_id') != p['packet_id']: raise Invalid('packet identity mismatch')
        docs = p['packet'].get('documents')
        if not isinstance(docs, list) or not docs: raise Invalid('review packet needs documents')
        if any(not isinstance(d, dict) or not isinstance(d.get('id'), str) or not isinstance(d.get('text'), str) for d in docs):
            raise Invalid('invalid packet source')
        if len({d['id'] for d in docs}) != len(docs): raise Invalid('duplicate document ID')
        packets[p['packet_id']] = p
    if not isinstance(context['candidates'], list): raise Invalid('candidate array required')
    candidates = {}
    for c in context['candidates']:
        obj(c, {'candidate_id', 'packet_id', 'candidate_sha256', 'raw_response', 'generation_status'}, 'context candidate')
        if c['candidate_id'] in candidates or c['packet_id'] not in packets or not isinstance(c['raw_response'], str):
            raise Invalid('duplicate/foreign/nontext candidate')
        text(c['candidate_id'], 'candidate ID'); text(c['generation_status'], 'candidate execution status')
        if digest_json({k:v for k,v in c.items() if k != 'candidate_sha256'}) != c['candidate_sha256']:
            raise Invalid('candidate hash mismatch')
        candidates[c['candidate_id']] = c
    return packets, candidates


def validate_registry(registry, context):
    obj(registry, {'schema_version', 'pilot_id', 'coordinator_attestation', 'reviewers', 'reference_round1_locked'}, 'registry')
    if registry['schema_version'] != VERSION or registry['pilot_id'] != context['pilot_id'] or registry['coordinator_attestation'] is not True:
        raise Invalid('matching coordinator-attested registry required')
    if type(registry['reference_round1_locked']) is not bool: raise Invalid('invalid reference lock')
    packets, candidates = validate_context(context)
    if not isinstance(registry['reviewers'], list): raise Invalid('reviewer array required')
    reviewers = {}
    for r in registry['reviewers']:
        obj(r, {'reviewer_code', 'role', 'human_origin_attested', 'credentials_checked',
                'independence_checked', 'consent_to_process', 'reference_assignments', 'candidate_assignments'}, 'registered reviewer')
        code(r['reviewer_code'])
        if r['reviewer_code'] in reviewers: raise Invalid('duplicate registered reviewer')
        if r['role'] not in ('domain', 'methods', 'formal'): raise Invalid('invalid reviewer role')
        if any(r[k] is not True for k in ('human_origin_attested', 'credentials_checked', 'independence_checked', 'consent_to_process')):
            raise Invalid('incomplete coordinator eligibility/consent checks')
        strings(r['reference_assignments'], 'reference assignments', packets)
        strings(r['candidate_assignments'], 'candidate assignments', candidates)
        reviewers[r['reviewer_code']] = r
    return reviewers


def validate_submission(form, registry, context, *, allow_test_fixtures=False):
    reviewers = validate_registry(registry, context); packets, candidates = validate_context(context)
    obj(form, {'schema_version', 'pilot_id', 'origin', 'stage', 'round', 'reviewer_code',
               'declaration', 'prior_form_sha256', 'tools_and_external_sources', 'judgments'}, 'submission')
    if form['schema_version'] != VERSION or form['pilot_id'] != context['pilot_id']: raise Invalid('wrong pilot/version')
    if form['origin'] not in (('human', 'software_test_fixture') if allow_test_fixtures else ('human',)):
        raise Invalid('production ingestion accepts only attested human-origin submissions')
    code(form['reviewer_code'])
    if form['reviewer_code'] not in reviewers: raise Invalid('unregistered reviewer')
    if type(form['round']) is not int or form['round'] not in (1, 2) or form['stage'] not in ('reference', 'candidate'):
        raise Invalid('invalid stage or review round')
    if form['stage'] == 'candidate' and not registry['reference_round1_locked']:
        raise Invalid('candidate ratings require coordinator lock of reference first round')
    d = form['declaration']; obj(d, DECLARATION_KEYS, 'declaration')
    if d['human_attestation'] is not (form['origin'] == 'human'): raise Invalid('origin/attestation conflict')
    if type(d['independent_work']) is not bool or type(d['saw_other_reviews']) is not bool:
        raise Invalid('independence declarations must be booleans')
    if form['round'] == 1 and (not d['independent_work'] or d['saw_other_reviews']):
        raise Invalid('first-round judgments must precede shared discussion')
    for k in ('source_exposure', 'author_label_exposure', 'candidate_identity_exposure'):
        if d[k] not in ('none', 'some', 'uncertain'): raise Invalid('explicit exposure declaration required')
    text(d['conflicts'], 'conflict declaration, including explicit none'); text(d['expertise_scope'], 'expertise declaration')
    strings(form['tools_and_external_sources'], 'tools and supplemental sources')
    prior = form['prior_form_sha256']
    if (form['round'] == 1 and prior is not None) or (form['round'] == 2 and (not isinstance(prior, str) or re.fullmatch('[a-f0-9]{64}', prior) is None)):
        raise Invalid('round two requires immutable first-round form digest')
    if not isinstance(form['judgments'], list) or not form['judgments'] or len(form['judgments']) > 100:
        raise Invalid('bounded nonempty judgments required; missing assignments are not fabricated ratings')
    seen = set(); r = reviewers[form['reviewer_code']]
    for j in form['judgments']:
        reference = form['stage'] == 'reference'
        obj(j, REFERENCE_JUDGMENT if reference else CANDIDATE_JUDGMENT, 'judgment')
        pid = j['packet_id']
        if not isinstance(pid, str) or pid not in packets or j['packet_sha256'] != packets[pid]['packet_sha256']:
            raise Invalid('foreign packet or changed scientific envelope')
        key = pid if reference else j['candidate_id']
        if not isinstance(key, str) or key in seen: raise Invalid('duplicate judgment')
        seen.add(key)
        if key not in r['reference_assignments' if reference else 'candidate_assignments']:
            raise Invalid('judgment outside coordinator assignment')
        if not reference:
            c = candidates[key]
            if c['packet_id'] != pid or c['candidate_sha256'] != j['candidate_sha256']:
                raise Invalid('candidate identity/hash mismatch')
        if j['assessment_status'] not in ('completed', 'unable_to_assess'): raise Invalid('invalid assessment status')
        if j['reviewer_uncertainty'] not in UNCERTAINTIES: raise Invalid('reviewer uncertainty required')
        text(j['rationale'], 'scientific rationale')
        citations = j['citations']; docs = {d['id']:d['text'] for d in packets[pid]['packet']['documents']}
        if not isinstance(citations, list) or len(citations) > 100: raise Invalid('citation array required')
        if j['assessment_status'] == 'completed' and not citations: raise Invalid('completed judgment needs source attribution')
        for cite in citations:
            obj(cite, {'document_id', 'locator', 'quotation'}, 'citation')
            if not isinstance(cite['document_id'], str) or cite['document_id'] not in docs:
                raise Invalid('nonsupplied scientific document ID')
            text(cite['locator'], 'source locator')
            if not isinstance(cite['quotation'], str) or (cite['quotation'] and cite['quotation'] not in docs[cite['document_id']]):
                raise Invalid('altered/nontext quotation; exact substring required when provided')
        if reference:
            strings(j['legacy_labels'], 'legacy labels', LABELS); strings(j['missing_assumptions'], 'missing assumptions')
            strings(j['issues'], 'scientific issue types', ISSUES)
            if j['category_relation'] not in (*CATEGORY_RELATIONS, 'not_assessable'): raise Invalid('category relation required')
            n = len(j['legacy_labels'])
            if ((j['category_relation'] == 'single_defensible' and n != 1) or
                (j['category_relation'] in ('simultaneously_applicable', 'alternative_interpretations') and n < 2) or
                (j['category_relation'] in ('none_fit', 'not_assessable') and n != 0)):
                raise Invalid('label set/category relation inconsistent')
            if j['evidence_relation'] not in (*RELATIONS, 'not_assessable'): raise Invalid('invalid evidence relation')
            if j['assessment_status'] == 'completed' and (j['category_relation'] == 'not_assessable' or j['evidence_relation'] == 'not_assessable'):
                raise Invalid('completed judgment cannot use unassessable reference dimensions')
            if j['assessment_status'] == 'unable_to_assess' and (j['legacy_labels'] or j['category_relation'] != 'not_assessable' or j['evidence_relation'] != 'not_assessable'):
                raise Invalid('unable-to-assess reference cannot assert rated categories')
            text(j['supported_scope'], 'scope or explicit no established scope'); text(j['uncertainty_explanation'], 'uncertainty explanation')
            if j['proposed_disposition'] not in ('retain', 'clarify', 'reference_correction_proposed', 'preserve_ambiguity', 'exclude', 'unable_to_assess'):
                raise Invalid('unknown proposed disposition')
            if j['proposed_revision'] is not None: text(j['proposed_revision'], 'proposed revision')
            if j['proposed_disposition'] == 'reference_correction_proposed' and ('reference_error_suspected' not in j['issues'] or not j['citations']):
                raise Invalid('proposed reference correction requires allegation and evidence')
        else:
            dimensions = {'reasoning_validity':('valid','partly_valid','invalid','not_assessable'),
                'attribution_validity':('supported','unsupported','missing','not_assessable'),
                'scope_handling':('adequate','inadequate','not_assessable'),
                'uncertainty_handling':('adequate','inadequate','not_assessable')}
            for k, options in dimensions.items():
                if j[k] not in options: raise Invalid('invalid candidate rating')
                if j['assessment_status'] == 'unable_to_assess' and j[k] != 'not_assessable':
                    raise Invalid('unable-to-assess candidate cannot assert quality ratings')
    return form


def nominal_kappa(left, right):
    if len(left) != len(right): raise Invalid('agreement requires paired values')
    n = len(left)
    if not n: return {'n':0, 'observed_agreement':None, 'expected_agreement':None, 'kappa':None}
    a,b = Counter(left),Counter(right)
    po = sum(x==y for x,y in zip(left,right))/n
    pe = sum(a[k]*b[k] for k in a.keys() | b.keys())/(n*n)
    return {'n':n, 'observed_agreement':po, 'expected_agreement':pe,
            'kappa':(po-pe)/(1-pe) if pe != 1 else None}


def analyze(forms, registry, context, *, allow_test_fixtures=False):
    reviewers = validate_registry(registry, context); packets,candidates = validate_context(context)
    if not isinstance(forms, list): raise Invalid('forms array required')
    records = {}; submitted = {}; hashes = {}
    for f in forms:
        validate_submission(f, registry, context, allow_test_fixtures=allow_test_fixtures)
        header = f['reviewer_code'], f['stage'], f['round']
        if header in submitted: raise Invalid('one immutable form per reviewer/stage/round; duplicate form')
        submitted[header] = f; hashes[digest_json(f)] = f
        for j in f['judgments']:
            key = j['packet_id'] if f['stage']=='reference' else j['candidate_id']
            records[header+(key,)] = j
    for f in forms:
        if f['round'] == 2:
            prev = hashes.get(f['prior_form_sha256'])
            if prev is None or prev['round'] != 1 or (prev['reviewer_code'],prev['stage']) != (f['reviewer_code'],f['stage']):
                raise Invalid('round-two link must identify supplied immutable matching first round')
            key = 'packet_id' if f['stage']=='reference' else 'candidate_id'
            if not {j[key] for j in f['judgments']} <= {j[key] for j in prev['judgments']}:
                raise Invalid('round two cannot introduce cases without first-round judgment')
    pairwise=[]; item_summary=[];coverage=[]
    for stage in ('reference','candidate'):
        assignment = 'reference_assignments' if stage=='reference' else 'candidate_assignments'
        expected = {(code,k) for code,r in reviewers.items() for k in r[assignment]}
        for round_ in (1,2):
            actual = {(code,k) for (code,s,rd,k) in records if s==stage and rd==round_}
            completed = {(code,k) for code,k in actual if records[(code,stage,round_,k)]['assessment_status']=='completed'}
            coverage.append({'stage':stage,'round':round_,'assigned':len(expected),'submitted':len(actual),'completed':len(completed),'unable_to_assess':len(actual-completed),'missing_assignments':len(expected-actual),'round_two_optional':round_==2})
            for a,b in combinations(sorted(reviewers),2):
                joint = sorted(set(reviewers[a][assignment]) & set(reviewers[b][assignment]))
                rs = [(records.get((a,stage,round_,k)),records.get((b,stage,round_,k))) for k in joint]
                usable = [(x,y) for x,y in rs if x and y and x['assessment_status']==y['assessment_status']=='completed']
                if not usable and not joint: continue
                row={'stage':stage,'round':round_,'reviewers':[a,b],'roles':[reviewers[a]['role'],reviewers[b]['role']],
                     'joint_assigned':len(joint),'joint_completed':len(usable),'excluded_missing_or_unassessable':len(joint)-len(usable)}
                if stage=='reference':
                    sets=[(set(x['legacy_labels']),set(y['legacy_labels'])) for x,y in usable]
                    js=[len(x&y)/len(x|y) for x,y in sets if x|y]
                    singles=[(x['legacy_labels'][0],y['legacy_labels'][0]) for x,y in usable if x['category_relation']==y['category_relation']=='single_defensible']
                    row.update({'exact_set_agreement':sum(x==y for x,y in sets)/len(sets) if sets else None,
                       'mean_jaccard_nonempty_union':sum(js)/len(js) if js else None,'jaccard_n':len(js),'jaccard_empty_union_excluded':len(sets)-len(js),
                       'category_relation_kappa':nominal_kappa([x['category_relation'] for x,y in usable],[y['category_relation'] for x,y in usable]),
                       'singleton_only_legacy_kappa':nominal_kappa([x for x,y in singles],[y for x,y in singles]),
                       'singleton_selection_excluded':len(usable)-len(singles),
                       'evidence_relation_kappa':nominal_kappa([x['evidence_relation'] for x,y in usable],[y['evidence_relation'] for x,y in usable])})
                else:
                    row['dimension_agreement']={k:nominal_kappa([x[k] for x,y in usable],[y[k] for x,y in usable]) for k in ('reasoning_validity','attribution_validity','scope_handling','uncertainty_handling')}
                pairwise.append(row)
            if stage=='reference':
                for pid,p in packets.items():
                    js=[(code,records[(code,stage,round_,pid)]) for code in reviewers if (code,stage,round_,pid) in records]
                    usable=[j for _,j in js if j['assessment_status']=='completed']; issues=Counter(i for j in usable for i in j['issues'])
                    item_summary.append({'packet_id':pid,'source_family':p['source_family'],'round':round_,
                        'submitted':len(js),'completed':len(usable),'legacy_label_sets':[sorted(j['legacy_labels']) for j in usable],
                        'label_set_disagreement':len({tuple(sorted(j['legacy_labels'])) for j in usable})>1,
                        'evidence_relation_disagreement':len({j['evidence_relation'] for j in usable})>1,
                        'issue_counts':dict(issues),'reference_error_status':'alleged_requires_independent_check' if issues['reference_error_suspected'] else 'none_alleged',
                        'irreconcilable_ambiguity_reported':bool(issues['irreconcilable_interpretation']),
                        'automatic_reference_revision':False})
    fixture = any(f['origin'] != 'human' for f in forms)
    return {'schema_version':VERSION,'pilot_id':context['pilot_id'],'analysis_kind':'SOFTWARE_FIXTURE_NOT_HUMAN_REVIEW' if fixture else 'coordinator_attested_human_records' if forms else 'NO_REVIEWS',
        'human_reviewers_with_submissions':len({f['reviewer_code'] for f in forms if f['origin']=='human'}),
        'human_judgments_submitted':sum(len(f['judgments']) for f in forms if f['origin']=='human'),
        'registered_reviewer_count':len(reviewers),'form_digests':sorted(hashes),'coverage':coverage,'pairwise':pairwise,'items':item_summary,
        'source_family_counts':dict(Counter(p['source_family'] for p in packets.values())),
        'planned_reference_role_slots':3*len(packets),
        'registered_reference_role_coverage':[{ 'packet_id':pid,
            'domain_assigned':sum(r['role']=='domain' and pid in r['reference_assignments'] for r in reviewers.values()),
            'methods_assigned':sum(r['role']=='methods' and pid in r['reference_assignments'] for r in reviewers.values()),
            'formal_supplement_assigned':sum(r['role']=='formal' and pid in r['reference_assignments'] for r in reviewers.values()),
            'unassigned_minimum_role_slots':max(0,2-sum(r['role']=='domain' and pid in r['reference_assignments'] for r in reviewers.values()))+max(0,1-sum(r['role']=='methods' and pid in r['reference_assignments'] for r in reviewers.values()))} for pid in packets],
        'exposure_declarations':[{'reviewer_code':f['reviewer_code'],'stage':f['stage'],'round':f['round'],'source':f['declaration']['source_exposure'],'author_labels':f['declaration']['author_label_exposure'],'candidate_identity':f['declaration']['candidate_identity_exposure']} for f in forms],
        'validated_forms':forms,'automatic_gold_created':False,
        'limits':['Attestations do not authenticate identity or establish expertise independently','Exact quotations/IDs do not establish source entailment','Purposive related cases and repeated reviewer pairs are not iid samples','Kappa is marginal/prevalence-sensitive; singleton-only kappa selects easier categorical judgments','No confidence intervals, expert validation claim or majority-vote gold','Missing assignments and unable-to-assess remain distinct; round two is optional','Public packet filtering does not establish blinding; exposure declarations retained']}


def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--context',type=Path,required=True);p.add_argument('--registry',type=Path,required=True)
    p.add_argument('--forms',type=Path,nargs='*',default=[]);p.add_argument('--output',type=Path,required=True);a=p.parse_args()
    try:
        output=a.output.resolve()
        if output.exists(): raise Invalid('refuse overwrite; preserve prior review records')
        if output.is_relative_to(ROOT) and not output.is_relative_to(ROOT/'results/local'):
            raise Invalid('actual review output inside repository must remain in ignored results/local')
        report=analyze([load_file(f) for f in a.forms],load_file(a.registry),load_file(a.context))
        report['input_file_sha256']={str(f):digest_bytes(f.read_bytes()) for f in [a.context,a.registry,*a.forms]}
        output.parent.mkdir(parents=True,exist_ok=True)
        with output.open('x') as f:json.dump(report,f,sort_keys=True,indent=2,allow_nan=False);f.write('\n')
        print(json.dumps({'output':str(output),'human_judgments':report['human_judgments_submitted'],'automatic_gold_created':False}))
    except (Invalid,OSError,ValueError,KeyError,TypeError) as e:p.exit(2,str(e)+'\n')
if __name__=='__main__':main()
